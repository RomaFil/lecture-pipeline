# Маркер між фрагментами. Пояснений у FORMAT_NOTE: без цього модель бачить різкий
# стрибок теми посеред тексту й може вирішити, що це два різні заняття.
SAMPLE_MARKER = "\n\n[...пропущено середину; далі фрагмент ІЗ ТОГО САМОГО заняття...]\n\n"
# Нижче цього відношення довжини до бюджету зріз не має сенсу — див. sample_text().
# 2.0 обране з запасом: реальні транскрипти починаються від ~12 000 символів
# (44-хвилинний запис) і доходять до ~230 000 (тригодинний), тобто всі вони
# впевнено за порогом, а поруч із ним опиняється лише щось аномально коротке.
SAMPLE_MIN_RATIO = 2.0


def _trim_tail(chunk: str, min_keep: float = 0.6) -> str:
    """Обрізає хвіст до кінця останнього завершеного речення."""
    best = max(chunk.rfind(". "), chunk.rfind("! "), chunk.rfind("? "))
    if best >= len(chunk) * min_keep:
        return chunk[:best + 1]
    sp = chunk.rfind(" ")
    return chunk[:sp] if sp > 0 else chunk


def _trim_head(chunk: str, max_skip: float = 0.4) -> str:
    """Прибирає початок до першого завершеного речення, щоб не стартувати з півслова."""
    limit = int(len(chunk) * max_skip)
    best = -1
    for sep in (". ", "! ", "? "):
        i = chunk.find(sep)
        if 0 <= i <= limit and i > best:
            best = i
    if best >= 0:
        return chunk[best + 2:]
    sp = chunk.find(" ")
    return chunk[sp + 1:] if 0 <= sp <= limit else chunk


def sample_text(transcript: str, max_chars: int = 5000) -> str:
    """Зріз транскрипту для класифікатора: половина з початку, половина з середини.

    ЧОМУ НЕ ПЕРШІ N СИМВОЛІВ. Доти бралось `transcript[:5000]` — приблизно перші
    15-20 хвилин мовлення. Для півторагодинної пари цього досить: тему оголошують
    на початку. Для довгого заняття з оргвступом — ні, і 09.09.2026 це показав
    живий випадок: тригодинний запис стажування, де три години розбирали Linux і
    FHS, отримав тему «Презентація про компанію AJAX» — бо саме цим починались
    перші двадцять хвилин. Дисципліна була правильна, а тема описувала зачин.

    ЧОМУ САМЕ ПОЧАТОК + СЕРЕДИНА. Ці дві частини потрібні для різного:
      початок  — для `subject`: вітання, назва предмета, «продовжуємо тему»;
      середина — для `topic`: там уже зміст, без оргмоментів.
    Бюджет лишається той самий, тому контекст, швидкість і памʼять не змінюються —
    змінюється лише те, ЗВІДКИ беруться символи.

    Короткий транскрипт не чіпається взагалі: до `max_chars` повертається як є,
    байт у байт. Саме тому всі наявні фікстури поводяться точно так само.

    Ріжеться по межі РЕЧЕННЯ, а не рядка: `plain` із transcribe_worker — це
    суцільний рядок (`" ".join(...)`), переносів у ньому немає.
    """
    text = transcript.strip()
    if len(text) <= max_chars:
        return text
    if len(text) <= max_chars * SAMPLE_MIN_RATIO:
        # Трохи довший за бюджет, але недостатньо, щоб ділити мало сенс: середина
        # опинилась би впритул до початку або перекрилась би з ним. Просте обрізання.
        # SAMPLE_MIN_RATIO існував з появи sample_text(), але ніде не застосовувався —
        # знайдено тестом (test_process.py), а не збоєм: 09.09.2026 усі реальні
        # транскрипти довші за поріг, тому в бою це мовчало.
        return _trim_tail(text[:max_chars])

    head_budget = max_chars // 2
    mid_budget = max_chars - head_budget - len(SAMPLE_MARKER)

    head = _trim_tail(text[:head_budget])

    mid_from = max(len(head), len(text) // 2 - mid_budget // 2)
    mid = _trim_head(_trim_tail(text[mid_from:mid_from + mid_budget]))

    return head + SAMPLE_MARKER + mid


