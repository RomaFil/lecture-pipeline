#!/usr/bin/env python3
"""Класифікація лекційного транскрипту за закритим списком дисциплін.

Локальна LLM через Ollama на 127.0.0.1. Вільної генерації назви дисципліни немає:
модель вибирає код зі списку або повертає НЕВІДОМО — вгадувати заборонено.
"""
import json
import os
import re
import sys

import requests

OLLAMA = os.getenv("OLLAMA_URL", "http://127.0.0.1:11434")
MODEL = os.getenv("LECTURE_LLM", "qwen2.5:7b-instruct-q4_K_M")
# 0 = вивантажити модель одразу після відповіді (RAM потрібна whisper).
# Для пакетних тестів можна виставити "5m", щоб не перезавантажувати щоразу.
KEEP_ALIVE = os.getenv("LECTURE_KEEP_ALIVE", "0")

# Закритий список: тільки дисципліни, де пара проходить онлайн (осінь 2026/2027).
# Код — семантичний рядок, а не число: малій моделі значно легше вибрати "МАТАНАЛІЗ"
# за змістом, ніж згадати, що математичний аналіз — це «4».
# slug — ім'я підпапки у Brain/raw/lectures/ та ~/lectures/outgoing/
SUBJECTS = {
    "СХЕМОТЕХНІКА": ("Схемотехніка. Частина 1. Електронні компоненти", "Схемотехніка"),
    "ТЕОРІЯ_КІЛ": ("Основи теорії кіл", "Основи теорії кіл"),
    "ФІЗИКА": ("Загальна фізика. Частина 2", "Загальна фізика"),
    "МАТАНАЛІЗ": ("Математичний аналіз. Частина 3", "Математичний аналіз"),
    "МЕРЕЖІ_CISCO": ("Комп'ютерні мережі та безпека за технологіями CISCO", "Мережі CISCO"),
}
UNKNOWN = "НЕВІДОМО"

# Порядок полів має значення: JSON-граматика змушує генерувати їх саме в цьому
# порядку. Спершу модель виписує ключові терміни й тему (тобто «думає вголос»),
# і лише потім комітиться на код дисципліни. Якщо код стоїть першим, мала модель
# мусить вгадати його нульовим токеном — і стабільно промахується.
SCHEMA = {
    "type": "object",
    "properties": {
        "keywords": {"type": "string", "maxLength": 120},
        "topic": {"type": "string", "maxLength": 70},
        # "практика" додана 07.09.2026 разом із дистанційкою: практики й
        # семінари переїхали з аудиторій у Zoom і тепер теж пишуться. Доти
        # enum знав лише лекцію й лабораторну, тож розбір задач біля дошки
        # неминуче ставав "лекцією" — поле було, але на практиках брехало.
        "kind": {"type": "string",
                 "enum": ["лекція", "практика", "лабораторна", "невідомо"]},
        "subject": {"type": "string", "enum": [*SUBJECTS, UNKNOWN]},
        "confidence": {"type": "string", "enum": ["high", "low"]},
    },
    "required": ["keywords", "topic", "kind", "subject", "confidence"],
    "additionalProperties": False,
}

SYSTEM = """Ти класифікуєш стенограми університетських занять (КПІ, радіотехнічний факультет).
Відповідай ВИКЛЮЧНО валідним JSON за схемою. Українською мовою.

Поле subject — рівно одне значення з цього списку:
СХЕМОТЕХНІКА — діоди, транзистори, підсилювачі, ключі, стабілітрони, ВАХ, операційні підсилювачі, логічні елементи, робоча точка, коефіцієнт передачі струму
ТЕОРІЯ_КІЛ — закони Кірхгофа, метод контурних струмів, RLC-кола, комплексний опір, перехідні процеси, резонанс, чотириполюсники, ЕРС, вітки і вузли
ФІЗИКА — електрика, магнетизм, оптика, коливання і хвилі, електромагнітна індукція, закон Фарадея, правило Ленца, інтерференція, дифракція, рівняння Максвелла
МАТАНАЛІЗ — числові та функціональні ряди, збіжність і розбіжність, ознака Даламбера, ознака Коші, гармонічний ряд, кратні та криволінійні інтеграли, градієнт, дивергенція, ротор, ряд Тейлора, диференціальні рівняння
МЕРЕЖІ_CISCO — IP-адресація, підмережі, маска підмережі, маршрутизація, VLAN, комутатори, роутери, модель OSI, ACL, Packet Tracer, мережеві протоколи
НЕВІДОМО — зміст не належить до жодної з дисциплін вище

ПРАВИЛА:
- keywords заповнюй ПЕРШИМ: 5-8 ключових термінів прямо зі стенограми, через кому. Це твій чорновий аналіз.
- topic: 3-6 слів українською, конкретна тема саме цього заняття. Без назви дисципліни, без дати, без слів "лекція"/"практика"/"лабораторна".
- kind — рівно одне з чотирьох:
  "лекція" — теоретичний виклад нового матеріалу, означення, виведення формул;
  "практика" — розвʼязування задач, розбір домашнього завдання, семінар біля дошки, приклади з номерами із задачника;
  "лабораторна" — виконання лабораторної роботи, налаштування обладнання чи програми (Packet Tracer, Multisim), зняття вимірів, оформлення протоколу;
  "невідомо" — якщо з тексту тип заняття не видно.
  Тип НЕ впливає на subject: практика з матаналізу — це все одно МАТАНАЛІЗ.
- subject заповнюй ОСТАННІМ, спираючись на вже виписані keywords. Порівняй їх зі списком термінів кожної дисципліни й вибери той, де збігів найбільше.
- Якщо keywords не збігаються з жодною дисципліною зі списку — став subject="НЕВІДОМО" і confidence="low". НЕ ВГАДУЙ.
- Заняття з іноземної мови, спорту, кулінарії, побутові розмови — це завжди НЕВІДОМО.
- Якщо вагаєшся між двома дисциплінами — теж НЕВІДОМО.
"""


def classify(transcript: str, max_chars: int = 5000) -> dict:
    """Повертає {"ok": True, subject, slug, kind, topic} або {"ok": False, reason}."""
    text = transcript.strip()[:max_chars]
    r = requests.post(
        f"{OLLAMA}/api/chat",
        json={
            "model": MODEL,
            "messages": [
                {"role": "system", "content": SYSTEM},
                {"role": "user", "content": "Стенограма заняття:\n\n" + text},
            ],
            "format": SCHEMA,
            "stream": False,
            "keep_alive": KEEP_ALIVE,
            # num_predict — страховка від зациклення малої моделі:
            # відповідь за схемою вкладається у ~80 токенів.
            "options": {"temperature": 0, "num_predict": 250,
                        "num_ctx": 8192, "repeat_penalty": 1.1},
        },
        timeout=1800,
    )
    r.raise_for_status()
    data = json.loads(r.json()["message"]["content"])

    code = str(data.get("subject", UNKNOWN))
    conf = data.get("confidence", "low")
    topic = re.sub(r"\s+", " ", str(data.get("topic", ""))).strip(" .,;:-—")
    topic = re.sub(r'[\\/:*?"<>|]', "", topic)[:70]

    if code not in SUBJECTS or conf != "high" or not topic:
        return {
            "ok": False,
            "reason": f"subject={code} confidence={conf} topic={topic!r}",
            "raw": data,
        }
    full, slug = SUBJECTS[code]
    return {
        "ok": True,
        "subject": full,
        "slug": slug,
        "kind": data.get("kind", "невідомо"),
        "topic": topic,
        "raw": data,
    }


if __name__ == "__main__":
    src = sys.stdin.read() if len(sys.argv) < 2 else open(sys.argv[1], encoding="utf-8").read()
    print(json.dumps(classify(src), ensure_ascii=False, indent=2))
