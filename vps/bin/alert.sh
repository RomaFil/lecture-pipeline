#!/bin/bash
# Сторож конвеєра лекцій. Cron кожні 15 хв.
#
# НАВІЩО. Усі перші три інциденти Роман знайшов сам, помітивши, що чогось нема;
# 003 — через 20 годин, коли транскрипти цілу ніч пролежали в outgoing і про це
# не знав ніхто. Логи фіксували все правильно, але логи ніхто не читає.
#
# ЧОМУ НА VPS, А НЕ НА ПК. Помітити ВІДСУТНІСТЬ може лише той, хто не спить.
# ПК на Modern Standby сам є частиною проблеми: коли він не прокидається,
# він не може й поскаржитись. VPS увімкнений завжди.
#
# Кожна умова має свій ключ і кулдаун, щоб не перетворити алерти на шум:
# повторний алерт по тій самій умові — не частіше ніж раз на COOLDOWN_MIN.
# Коли умова зникає, штамп прибирається — тож рецидив прилетить одразу.

set -u

BASE="$HOME/lectures"
STATE="$BASE/state/alerts"
NOTIFY="$BASE/bin/notify.sh"

COOLDOWN_MIN=360          # 6 год між повторами того самого алерту
OUTGOING_STUCK_MIN=180    # транскрипт готовий, але ПК його не забирає
# Вікно, у якому перевірка 1 має право кричати. Уночі транскрипт у outgoing —
# це норма, а не збій: з дистанційки (07.09.2026) четвер дає ~6 год аудіо, черга
# завершується близько 01:00, а найближчий pull — аж о 09:00. Без цього вікна
# кожен четвер давав би хибний алерт о 04:00, а сторож, який регулярно бреше,
# вчить себе ігнорувати. Кінець вікна — 10, а не 9: слоту синка о 09:00 треба
# дати цілу годину, інакше алерт спрацює в перегонах із ним.
OUTGOING_QUIET_END=10
OUTGOING_QUIET_START=23
INCOMING_STUCK_MIN=300    # відео залите, але не оброблене (і нічого не крутиться)
ARCHIVE_STUCK_DAYS=9      # RETENTION_DAYS=7 + запас: YouTube так і не підтвердив

# --- бекап сховища Obsidian ---
# Бекап робить окремий root-овий cron (obsidian_backup.sh о 03:00), не конвеєр.
# Сторож лише ДИВИТЬСЯ на результат: архіви лежать із правами на читання всім.
BACKUP_DIR="${LECTURE_BACKUP_DIR:-/var/backups/obsidian_archive/daily}"
BACKUP_STALE_H=36         # свіжий архів має зʼявлятись щодоби; 36 год = пропущено один
BACKUP_SAME_MAX=4         # скільки однакових діб поспіль ще можна списати на «не редагував»

# --- пороги боку ПК ---
PC_STALE_MIN=200          # синк ходить кожні 2 год; 200 хв = пропущено ~2 слоти
PC_QUIET_END=9            # до 09:00 мовчання ПК — норма, він спить
PC_QUIET_START=23
PC_DISK_MIN_GB=30        # підняте з 20 (07.09.2026): день дистанційки ≈ 1,6 ГБ на ПК
PC_PENDING_MAX_H=6        # записи лежать незалитими
PC_TIMEOUTS_MAX=3         # подій 329 за добу
PC_BATT_MIN=40            # відсотків перед ніччю

# Розклад записів: <день>:<скільки записів очікується за день>.
# date +%u: 1=пн 2=вт 3=ср 4=чт 5=пт 6=сб 7=нд.
#
# ЄДИНЕ джерело правди — і про те, які дні є днями пар, і про те, скільки
# записів у такий день має бути. Два окремі списки неминуче розʼїхались би,
# а розʼїзд між списком і реальністю ми вже ловили (інцидент 007).
#
# ВТ=1  матаналіз-практика 14:15. З 22.09 додається ЛР схемотехніки
#       (вівторки, дистанційно в Multisim) — тоді підняти до 2.
# ЧТ=4  фізика 10:25, матаналіз 12:20, ОТК 14:15-17:45 (здвоєна = 2 файли).
#       Схемотехніка о 8:30 сюди НЕ закладена: 03.09 вона не записалась,
#       і поки не підтверджено фактом — поріг лишається 4, а не 5.
# ПТ=1  CISCO 12:20. Вечірня пара 18:05 разова (4 і 18.09), не рутина.
# СБ=2  ОТК-практика 8:30 + фізика-практика 10:25. Обидві переїхали в Zoom
#       разом із дистанційкою. Третій слот 14:15 у ОТК чергується з
#       англійською (05.09 там була саме англійська), тому не закладаємо.
#       ЦЕ ОЧІКУВАННЯ ЩЕ НЕ ПІДТВЕРДЖЕНЕ ФАКТОМ — перша така субота 12.09.
#
# Це ПОРІГ «менше — підозріло», а не точний розклад. Завищити гірше, ніж
# занизити: алерт, що спрацьовує щотижня даремно, вчить себе ігнорувати.
# Після першого повного тижня дистанційки звірити з фактом і поправити.
#
# СР=1  бокс 14:15. Онлайн з дистанційкою (щотижня, щонайменше до 26.09.2026),
#       доти писався б у спортзалі 24 і не писався взагалі. Додано 09.09.2026
#       разом із дисципліною БОКС у classify.py. Коли повернуть офлайн —
#       ПРИБРАТИ звідси, інакше щосереди прилітатиме хибний алерт.
# ПН і НД пар немає.
#
# Ajax (вт/чт 17:00-20:00) сюди свідомо НЕ доданий, хоча дисципліна в
# classify.py тепер є. Заняття проходить офлайн і в онлайн переходить
# лише за тривоги — тобто запис є подією, а не рутиною. Поріг «менше N»
# карає саме за відсутність рутини, тож Ajax у списку давав би хибний алерт
# у кожен спокійний вівторок і четвер.
#
# Увага: англійська в суботу теж онлайн, але її немає в списку classify.py —
# якщо писати її в OBS, буде _needs-review і алерт 2 щосуботи.
LECTURE_SCHEDULE="2:1 3:1 4:4 5:1 6:2"
RECORDING_CHECK_HOUR=20   # пари закінчуються ~17:00, о 20:00 висновок надійний

mkdir -p "$STATE"

# fire <ключ> <текст> — надіслати з урахуванням кулдауну
fire() {
    local key="$1" text="$2" stamp="$STATE/$1.stamp" age
    if [ -f "$stamp" ]; then
        age=$(( ( $(date +%s) - $(stat -c %Y "$stamp") ) / 60 ))
        [ "$age" -lt "$COOLDOWN_MIN" ] && return 0
    fi
    "$NOTIFY" "$text" && touch "$stamp"
}

clear_alert() { rm -f "$STATE/$1.stamp"; }

# --- 1. Транскрипт лежить в outgoing і його не забирають ---------------------
# Саме цей випадок був в інциденті 003.
#
# Текст навмисно називає ПЕРЕВІРКУ, а не причину. До 09.09.2026 тут стояло
# "найімовірніше ПК не прокинувся, розблокуй екран" — і 08.09 це виявилось
# неправдою: ПК не спав, падала верифікація pull через дужки в імені файлу
# (інцидент 009). Порада відводила погляд рівно від того місця, де був баг.
# Правило: алерт має сказати, КУДИ ПОДИВИТИСЬ, а гіпотези — лише як варіанти
# тлумачення побаченого. Впевнена й хибна підказка гірша за її відсутність.
stuck_out=$(find "$BASE/outgoing" -type f -name '*.md' -mmin +$OUTGOING_STUCK_MIN 2>/dev/null | wc -l)
out_hour=$(date +%-H)
# Умова рахується завжди, а от кричати можна лише вдень. Знімати штамп теж
# дозволено цілодобово: інакше алерт, що погас уночі, лишався б "озброєним"
# до ранку і рецидив прилетів би не одразу, а через кулдаун.
if [ "$stuck_out" -gt 0 ] \
   && [ "$out_hour" -ge "$OUTGOING_QUIET_END" ] && [ "$out_hour" -lt "$OUTGOING_QUIET_START" ]; then
    names=$(find "$BASE/outgoing" -type f -name '*.md' -mmin +$OUTGOING_STUCK_MIN -printf '  %P\n' 2>/dev/null | head -5)
    fire outgoing_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: транскрипти не забирає ПК" \
        "" \
        "$stuck_out файл(ів) лежать у outgoing понад $((OUTGOING_STUCK_MIN/60)) год:" \
        "$names" \
        "" \
        "Спершу подивись ХВІСТ SYNC-ЛОГУ на ПК — він одразу розрізняє два випадки:"         "  є рядки pull з ERROR — синк ходить, але щось падає. Це НЕ сон."         "  рядків за останні години немає — ПК не прокидався, розблокуй екран.")"
elif [ "$stuck_out" -eq 0 ]; then
    clear_alert outgoing_stuck
fi

# --- 2. Класифікатор не впізнав дисципліну -----------------------------------
nrev=$(find "$BASE/_needs-review" -type f 2>/dev/null | wc -l)
if [ "$nrev" -gt 0 ]; then
    names=$(find "$BASE/_needs-review" -type f -printf '  %P\n' 2>/dev/null | head -5)
    fire needs_review "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: потрібен ручний розбір" \
        "" \
        "$nrev запис(ів) у _needs-review — класифікатор не впізнав дисципліну." \
        "$names" \
        "" \
        "Відео збережене, на YouTube не залите.")"
else
    clear_alert needs_review
fi

# --- 3. Відео залите, але не обробляється ------------------------------------
# Поки whisper крутиться, черга — це норма, не збій. Алерт лише коли нічого
# не працює, а файли лежать.
stuck_in=$(find "$BASE/incoming" -type f ! -name '*.uploading' -mmin +$INCOMING_STUCK_MIN 2>/dev/null | wc -l)
# Рахувати ТІЛЬКИ python конвеєра, за шляхом до скрипта. Просте `pgrep -c python`
# ловило все підряд: copyparty зі стека Music Cloud і app.poller з Air Alerts
# крутяться на VPS постійно, тому busy ніколи не дорівнював нулю — і перевірка
# не могла спрацювати в принципі. Знайдено тестом 07.09.2026; обидва сервіси
# зʼявились на VPS уже після того, як сторожа написали й "перевірили".
# Урок той самий, що в 005: зламана перевірка мовчить так само, як здорова.
busy=$(pgrep -c -f "$BASE/bin/(process|transcribe_worker)\.py" || true)
if [ "$stuck_in" -gt 0 ] && [ "${busy:-0}" -eq 0 ]; then
    names=$(find "$BASE/incoming" -type f ! -name '*.uploading' -mmin +$INCOMING_STUCK_MIN -printf '  %P\n' 2>/dev/null | head -5)
    fire incoming_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: обробка стоїть" \
        "" \
        "$stuck_in відео лежать в incoming понад $((INCOMING_STUCK_MIN/60)) год, і жоден python не працює:" \
        "$names" \
        "" \
        "Дивись ~/lectures/logs/process.log і run.log.")"
else
    clear_alert incoming_stuck
fi

# --- 4. Нові ERROR у process.log ---------------------------------------------
errfile="$STATE/process_errors.count"
# `grep -c` друкує "0" І виходить з кодом 1, коли збігів немає, тож звичне
# `|| echo 0` дописувало ДРУГИЙ нуль: у файл лягало "0\n0", а наступне
# порівняння [ 1 -gt "0\n0" ] падало з integer expression expected — у cron
# непомітно. Перевірка ламалась саме в тому стані, з якого мала починати:
# коли помилок ще жодної. Тому — санітизація обох чисел, а не `|| echo`.
cur=$(grep -c ' ERROR ' "$BASE/logs/process.log" 2>/dev/null || true)
[[ "$cur" =~ ^[0-9]+$ ]] || cur=0
if [ -f "$errfile" ]; then
    prev=$(cat "$errfile" 2>/dev/null || true)
    [[ "$prev" =~ ^[0-9]+$ ]] || prev=0
    if [ "$cur" -gt "$prev" ]; then
        lines=$(grep ' ERROR ' "$BASE/logs/process.log" 2>/dev/null | tail -3)
        fire process_error "$(printf '%s\n' \
            "⚠️ Конвеєр лекцій: нові помилки обробки" \
            "" \
            "$(( cur - prev )) нов(их) ERROR у process.log:" \
            "$lines")"
    else
        # Штамп ОБОВ'ЯЗКОВО знімати, коли нових помилок немає. Ця перевірка
        # довго була єдиною з одинадцяти без clear_alert — і мовчки з'їдала
        # помилки. Умова тут не стан, а подія («лічильник виріс»), тож штамп,
        # поставлений раз, лишався назавжди, а кулдаун 6 год глушив усе
        # наступне. Доведено на живому прикладі 09.09.2026: ERROR об 11:43
        # прилетів, а OOM о 12:11 — ні, бо штамп був віком 26 хвилин.
        # Тепер після спокійного прогону штамп зникає, і наступна помилка
        # доходить одразу — як і в решти десяти перевірок.
        clear_alert process_error
    fi
# Перший запуск: тільки запам'ятовуємо базу. Історичні помилки — не новина,
# і сторож, який на встановленні одразу кричить про минуле, вчить його ігнорувати.
fi
echo "$cur" > "$errfile"

# --- 5. Архів не порожніє: YouTube так і не підтвердив обробку ----------------
stuck_arch=$(find "$BASE/archive" -type f -mtime +$ARCHIVE_STUCK_DAYS 2>/dev/null | wc -l)
if [ "$stuck_arch" -gt 0 ]; then
    names=$(find "$BASE/archive" -type f -mtime +$ARCHIVE_STUCK_DAYS -printf '  %P\n' 2>/dev/null | head -5)
    fire archive_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: архів не порожніє" \
        "" \
        "$stuck_arch відео старші за $ARCHIVE_STUCK_DAYS днів усе ще в archive/ —" \
        "YouTube не підтвердив uploadStatus=processed:" \
        "$names" \
        "" \
        "Файли навмисно не видаляються."         "Перевірка: відкрий відео на YouTube за id зі state.db — якщо його там"         "немає або воно відхилене, лекція є лише в цьому архіві.")"
else
    clear_alert archive_stuck
fi

# =============================================================================
#  Перевірки боку ПК. ПК звітує фактами у state/pc-status.env на кожному синку,
#  судить усе одно VPS — щоб уся логіка алертів лишалась в одному місці, а на
#  ПК не треба було ані токена, ані порогів.
# =============================================================================
PCFILE="$BASE/state/pc-status.env"

pcval() { grep -m1 "^$1=" "$PCFILE" 2>/dev/null | cut -d= -f2- ; }

# ціла частина числа, стійка і до коми, і до крапки: ПК під українською
# локаллю одного разу вже прислав "36,4", і порівняння тихо не спрацювало
pcint() { local v; v=$(pcval "$1"); v="${v%%[.,]*}"; [ -n "$v" ] && printf '%s' "$v" || printf '%s' ""; }

if [ -f "$PCFILE" ]; then
    pc_age_min=$(( ( $(date +%s) - $(stat -c %Y "$PCFILE") ) / 60 ))
    hour=$(date +%-H)

    # --- 6. ПК не виходить на звʼязок у денні години -------------------------
    # Уночі мовчання — норма (він спить). Питання лише вдень.
    if [ "$hour" -ge "$PC_QUIET_END" ] && [ "$hour" -lt "$PC_QUIET_START" ] \
       && [ "$pc_age_min" -gt "$PC_STALE_MIN" ]; then
        fire pc_stale "$(printf '%s\n' \
            "⚠️ ПК не виходить на звʼязок" \
            "" \
            "Останній звіт від ПК — $(( pc_age_min / 60 )) год $(( pc_age_min % 60 )) хв тому." \
            "Синк мав би відзвітувати щонайменше кожні 2 год з 09:00 до 23:00." \
            "" \
            "Перевірка на ПК: хвіст sync-логу за сьогодні і LastTaskResult задачі."             "Немає рядків START — планувальник не запускав; є START без EXIT —"             "процес створили, але він не дожив.")"
    else
        [ "$pc_age_min" -le "$PC_STALE_MIN" ] && clear_alert pc_stale
    fi

    # --- 7. Місце на диску ПК ------------------------------------------------
    disk_free=$(pcint disk_free_gb)
    if [ -n "$disk_free" ] && [ "$disk_free" -ge 0 ] 2>/dev/null \
       && [ "$disk_free" -lt "$PC_DISK_MIN_GB" ]; then
        fire pc_disk "$(printf '%s\n' \
            "⚠️ Мало місця на ПК" \
            "" \
            "На C: лишилось $(pcval disk_free_gb) ГБ з $(pcval disk_total_gb)." \
            "Одна пара — 300-400 МБ. Забитий диск = OBS тихо не запише.")"
    else
        clear_alert pc_disk
    fi

    # --- 8. Записи лежать на ПК незалитими -----------------------------------
    # Дзеркало перевірки outgoing: VPS сам їх не бачить у принципі.
    p_old=$(pcint pending_oldest_h)
    p_cnt=$(pcval pending_count)
    if [ -n "$p_old" ] && [ "$p_old" -gt "$PC_PENDING_MAX_H" ] 2>/dev/null; then
        fire pc_pending "$(printf '%s\n' \
            "⚠️ Записи застрягли на ПК" \
            "" \
            "$p_cnt запис(ів) лежать у Videos\\Lectures вже $(pcval pending_oldest_h) год і не заливаються:" \
            "  $(pcval pending_names)" \
            "" \
            "Дивись хвіст sync-логу: чи є там ERROR або WARN про ssh.")"
    else
        clear_alert pc_pending
    fi

    # --- 9. Задачу регулярно вбиває таймліміт --------------------------------
    to=$(pcint task_timeouts_24h)
    if [ -n "$to" ] && [ "$to" -ge "$PC_TIMEOUTS_MAX" ] 2>/dev/null; then
        fire pc_timeouts "$(printf '%s\n' \
            "⚠️ Синк регулярно не встигає" \
            "" \
            "За добу задачу $to раз(и) вбито за ExecutionTimeLimit (подія 329)." \
            "Якщо між ними немає рядків ПІДТВЕРДЖЕНО — PT30M замалий," \
            "або щось стабільно висне. Це не самолікується.")"
    else
        clear_alert pc_timeouts
    fi

    # --- 10. Уночі ноут на батареї -------------------------------------------
    # Розряджений ноут не прокинеться жодним таймером — і це видно заздалегідь.
    if [ "$hour" -ge 21 ] && [ "$hour" -lt 23 ]; then
        ac=$(pcval on_ac); bat=$(pcint battery_pct)
        if [ "$ac" = "0" ] && [ -n "$bat" ] && [ "$bat" -lt "$PC_BATT_MIN" ] 2>/dev/null; then
            fire pc_battery "$(printf '%s\n' \
                "⚠️ ПК на батареї перед ніччю" \
                "" \
                "Заряд ${bat}%, живлення не підключене." \
                "Нічний запуск о 23:00 з великою ймовірністю не відбудеться." \
                "" \
                "Встав зарядку — це дешевше, ніж чекати транскрипти до ранку.")"
        else
            clear_alert pc_battery
        fi
    fi
fi

# --- 11. Був день пар, а жодного запису немає --------------------------------
# ЄДИНА відмова, яка й досі втрачає лекцію безповоротно: OBS не записав.
# Конвеєр знає лише про файли, які існують, тому без цієї перевірки мовчазна
# відсутність запису виглядає точно як вихідний.
# Дні пар — у LECTURE_DAYS на початку файлу, там же й обґрунтування кожного дня.
#
# Обмеження, про яке варто пам'ятати: перевірка питає "чи є хоч один запис", а
# не "чи всі". У четвер пар чотири-п'ять — відсутність однієї з них ця умова не
# побачить. Порахувати очікувану кількість на день — окрема правка (P2).
dow=$(date +%u)
hour=$(date +%-H)

# скільки записів очікуємо саме сьогодні (порожньо = сьогодні не день пар)
expect=""
for pair in $LECTURE_SCHEDULE; do
    [ "${pair%%:*}" = "$dow" ] && expect="${pair##*:}"
done

if [ -n "$expect" ] && [ "$hour" -ge "$RECORDING_CHECK_HOUR" ]; then
    today_iso=$(date +%F)
    # Рахуємо ВІДЕО, і кожне рівно один раз. Запис завжди лежить рівно в одному
    # місці: incoming (чекає обробки), archive (оброблено), _needs-review (не
    # впізнано класифікатором).
    #
    # outgoing свідомо НЕ рахуємо: транскрипт там відповідає відео, яке вже
    # полічене в archive, тобто одна лекція йшла за дві. Поки поріг був "хоч
    # щось", це було нешкідливо; для порогу "менше за N" — ламає все.
    # `! -name *.md` теж не косметика: у _needs-review поруч із відео лежить
    # нотатка, і її імʼя так само містить сьогоднішню дату.
    seen=$(find "$BASE/incoming" "$BASE/archive" "$BASE/_needs-review"                 -type f ! -name '*.md' -name "*$today_iso*" 2>/dev/null | wc -l)

    # Плюс те, що ще лежить на ПК і не доїхало. Перетину з попереднім немає:
    # ПК рахує лише файли, які ЗАРАЗ у теці, а після push він їх видаляє.
    pc_today=$(pcint recordings_today)
    if [ -n "$pc_today" ] && [ "$pc_today" -gt 0 ] 2>/dev/null; then
        seen=$(( seen + pc_today ))
    fi

    if [ "$seen" -eq 0 ]; then
        fire no_recording "$(printf '%s
'             "❓ Сьогодні день пар, а записів немає"             ""             "За $today_iso не знайшлось жодного запису — ні на VPS, ні в черзі на ПК."             "Очікувалось: $expect."             ""             "Якщо пари були — OBS не записав, і лекція втрачена безповоротно."             "Якщо пар не було — просто зігноруй.")"
    elif [ "$seen" -lt "$expect" ]; then
        fire no_recording "$(printf '%s
'             "❓ Записів менше, ніж мало бути"             ""             "За $today_iso знайдено $seen з $expect очікуваних."             ""             "Найімовірніше одну пару не записали — перевір, поки памʼятаєш, яку."             "Якщо пара просто не відбулась, постав правильне число в"             "LECTURE_SCHEDULE у ~/lectures/bin/alert.sh.")"
    else
        clear_alert no_recording
    fi
fi

# --- 12. Бекап сховища є, але не змінюється ----------------------------------
# НАВІЩО. У липні 2026 хардернінг прав забрав у бекапу доступ на читання, і той
# місяць складав порожні 45-байтні архіви. Це полагоджено перевіркою MIN_BYTES
# у самому obsidian_backup.sh. Але лишився ГІРШИЙ варіант тієї ж відмови:
# архів нормального розміру, який просто не змінюється, бо джерело застигло.
# Розмір у нормі, gzip цілий, файли щодня нові — і жодна перевірка не спрацює.
#
# Саме це знайшлось 09.09.2026 руками: obsidian_2026-09-08.tar.gz і
# obsidian_2026-09-09.tar.gz виявились ПОБАЙТОВО ідентичними. Не поломка бекапу —
# відставання клієнтського синку: Remotely Save штовхає зміни лише коли Obsidian
# відкритий, а ПК ці дні здебільшого спав. Наслідок практичний: транскрипт
# практики 08.09 і конспекти Ajax якийсь час існували в ОДНОМУ екземплярі, на ПК.
#
# Порівнюємо РОЗМІР, а не sha256: архіви по 400 МБ, хешувати їх щочверть години
# безглуздо. Збіг розмірів байт-у-байт кілька діб поспіль на 400-мегабайтному
# gzip практично неможливий, якщо джерело справді змінювалось.
if [ -d "$BACKUP_DIR" ]; then
    newest=$(ls -1t "$BACKUP_DIR"/*.tar.gz 2>/dev/null | head -1)
    if [ -n "$newest" ]; then
        b_age_h=$(( ( $(date +%s) - $(stat -c %Y "$newest" 2>/dev/null || date +%s) ) / 3600 ))
        # скільки найсвіжіших архівів мають однаковий розмір
        sizes=$(ls -1t "$BACKUP_DIR"/*.tar.gz 2>/dev/null | head -$(( BACKUP_SAME_MAX + 1 ))                 | xargs -r stat -c %s 2>/dev/null)
        n_total=$(printf '%s
' "$sizes" | grep -c . || true)
        n_uniq=$(printf '%s
' "$sizes" | sort -u | grep -c . || true)
        [[ "$n_total" =~ ^[0-9]+$ ]] || n_total=0
        [[ "$n_uniq" =~ ^[0-9]+$ ]] || n_uniq=0

        if [ "$b_age_h" -gt "$BACKUP_STALE_H" ]; then
            fire backup_stale "$(printf '%s
'                 "⚠️ Бекап сховища не оновлюється"                 ""                 "Найсвіжіший архів — $b_age_h год тому:"                 "  $(basename "$newest")"                 ""                 "Перевірка: чи ходить root-овий cron о 03:00 і чи читається джерело.")"
        elif [ "$n_total" -gt "$BACKUP_SAME_MAX" ] && [ "$n_uniq" -eq 1 ]; then
            fire backup_stale "$(printf '%s
'                 "⚠️ Бекап робиться, але сховище в ньому застигло"                 ""                 "$n_total останніх архівів мають ОДНАКОВИЙ розмір — джерело не змінюється."                 "Сам бекап справний, застряг клієнтський синк."                 ""                 "Перевірка: відкрий Obsidian і дай Remotely Save доробити."                 "Поки цього не сталось, свіжі нотатки існують в одному екземплярі — на ПК.")"
        else
            clear_alert backup_stale
        fi
    fi
fi

