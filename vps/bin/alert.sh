#!/bin/bash
# Сторож конвеєра лекцій. Cron кожні 15 хв.
#
# НАВІЩО. Усі перші три інциденти Роман знайшов сам, помітивши, що чогось нема;
# 003 — через 20 годин, коли транскрипти цілу ніч пролежали в outgoing і про це
# не знав ніхто. Логи фіксували все правильно, але логи ніхто не читає.
#
# ЧОМУ НА VPS, А НЕ НА ПК. Помітити ВІДСУТНІСТЬ може лише той, хто не спить.
# ПК на Modern Standby сам є частиною проблеми: коли він не прокидається,
# він не може й поскаржитись. VPS увімкнений завжди.
#
# Кожна умова має свій ключ і кулдаун, щоб не перетворити алерти на шум:
# повторний алерт по тій самій умові — не частіше ніж раз на COOLDOWN_MIN.
# Коли умова зникає, штамп прибирається — тож рецидив прилетить одразу.

set -u

BASE="$HOME/lectures"
STATE="$BASE/state/alerts"
NOTIFY="$BASE/bin/notify.sh"

COOLDOWN_MIN=360          # 6 год між повторами того самого алерту
OUTGOING_STUCK_MIN=180    # транскрипт готовий, але ПК його не забирає
# Вікно, у якому перевірка 1 має право кричати. Уночі транскрипт у outgoing —
# це норма, а не збій: з дистанційки (07.09.2026) четвер дає ~6 год аудіо, черга
# завершується близько 01:00, а найближчий pull — аж о 09:00. Без цього вікна
# кожен четвер давав би хибний алерт о 04:00, а сторож, який регулярно бреше,
# вчить себе ігнорувати. Кінець вікна — 10, а не 9: слоту синка о 09:00 треба
# дати цілу годину, інакше алерт спрацює в перегонах із ним.
OUTGOING_QUIET_END=10
OUTGOING_QUIET_START=23
INCOMING_STUCK_MIN=300    # відео залите, але не оброблене (і нічого не крутиться)
ARCHIVE_STUCK_DAYS=9      # RETENTION_DAYS=7 + запас: YouTube так і не підтвердив

# --- бекап сховища Obsidian ---
# Бекап робить окремий root-овий cron (obsidian_backup.sh о 03:00), не конвеєр.
# Сторож лише ДИВИТЬСЯ на результат: архіви лежать із правами на читання всім.
BACKUP_DIR="${LECTURE_BACKUP_DIR:-/var/backups/obsidian_archive/daily}"
BACKUP_STALE_H=36         # свіжий архів має зʼявлятись щодоби; 36 год = пропущено один
BACKUP_SAME_MAX=4         # скільки однакових діб поспіль ще можна списати на «не редагував»

# --- нічний apt-апдейт + ребут (root-крон, окремо від конвеєра) ---
# Той самий патерн, що бекап Obsidian вище: root-крон виробляє артефакт, ми
# лише ЧИТАЄМО (/var/log, root:root 644) — не запускаємо й не володіємо ним.
UPDATE_LOG="${LECTURE_UPDATE_LOG:-/var/log/vps-nightly-update.log}"
UPDATE_STALE_DAYS=30      # скільки днів без result=ok — сигнал розібратись
UPDATE_LOOKBACK=10        # скільки останніх result=-рядків читати для діагнозу причини

# --- пороги боку ПК ---
# 27.09.2026 (Роман): ПК свідомо не тримається ввімкненим, а від системних
# сигналів він не прокидається (003, 014). Тож «ПК спить» — норма, а не збій:
# мовчання ПК кричить лише через добу. Швидко ловиться тільки випадок «ПК на
# звʼязку, а транскрипти не забирає» (перевірка 1) — це вже поломка синку (009).
PC_STALE_MIN=1440         # ПК мовчить добу
PC_AWAKE_MIN=150          # ПК звітував нещодавно = не спить (синк кожні 2 год)
PC_QUIET_END=9            # до 09:00 мовчання ПК — норма, він спить
PC_QUIET_START=23
PC_DISK_MIN_GB=30        # підняте з 20 (07.09.2026): день дистанційки ≈ 1,6 ГБ на ПК
PC_PENDING_MAX_H=6        # записи лежать незалитими
PC_TIMEOUTS_MAX=3         # подій 329 за добу

# --- календар КПІ (timetable.py) ---
CAL_URL="$BASE/secrets/kpi_calendar.url"
CAL_CACHE="$BASE/state/kpi_calendar.ics"
CAL_STALE_H=48            # process.py оновлює кеш щонайменше раз на 6 год
AJAX_CAL_URL="$BASE/secrets/ajax_calendar.url"     # з 30.09.2026, інцидент 021
AJAX_CAL_CACHE="$BASE/state/ajax_calendar.ics"
# Скільки онлайн-пар за календарем має бути записано сьогодні (перевірка 11).
# Змінна середовища — щоб тест міг підставити число без мережі й Python.
EXPECT_CMD="${LECTURE_EXPECT_CMD:-$BASE/venv/bin/python $BASE/bin/timetable.py expect}"

# Прапорець обслуговування: файл із mtime У МАЙБУТНЬОМУ = до цього часу йде
# важкий тест, і «обробка стоїть» — очікувано. Ставиться так:
#   touch -d '+4 hours' ~/lectures/state/maintenance
# Минув час — прапорець сам перестає діяти, забути його зняти неможливо.
MAINT="$BASE/state/maintenance"

# Скільки записів очікується сьогодні — з календаря КПІ (EXPECT_CMD вище).
# До 27.09.2026 тут стояла статична таблиця «день:кількість», і на плаваючому
# розкладі вона давала гарантований хибний алерт щосуботи (16.09 — «Роман
# погодився ігнорувати»). Календар знає і перенесення, і скасування, і формат:
# рахуються лише онлайн-пари (поле «Місце»), бо офлайн OBS не пише. Ajax у
# календарі КПІ немає — запис Ajax є подією, а не рутиною, як і раніше.
RECORDING_CHECK_HOUR=20   # пари закінчуються ~17:00, о 20:00 висновок надійний

mkdir -p "$STATE"

# fire <ключ> <текст> — надіслати з урахуванням кулдауну
fire() {
    local key="$1" text="$2" stamp="$STATE/$1.stamp" age
    if [ -f "$stamp" ]; then
        age=$(( ( $(date +%s) - $(stat -c %Y "$stamp") ) / 60 ))
        [ "$age" -lt "$COOLDOWN_MIN" ] && return 0
    fi
    "$NOTIFY" "$text" && touch "$stamp"
}

clear_alert() { rm -f "$STATE/$1.stamp"; }

# --- 1. Транскрипт лежить в outgoing і його не забирають ---------------------
# Саме цей випадок був в інциденті 003.
#
# Текст навмисно називає ПЕРЕВІРКУ, а не причину. До 09.09.2026 тут стояло
# "найімовірніше ПК не прокинувся, розблокуй екран" — і 08.09 це виявилось
# неправдою: ПК не спав, падала верифікація pull через дужки в імені файлу
# (інцидент 009). Порада відводила погляд рівно від того місця, де був баг.
# Правило: алерт має сказати, КУДИ ПОДИВИТИСЬ, а гіпотези — лише як варіанти
# тлумачення побаченого. Впевнена й хибна підказка гірша за її відсутність.
#
# 27.09.2026: кричить лише коли ПК НА ЗВʼЯЗКУ (звітував за PC_AWAKE_MIN) —
# тобто синк ходить, а pull не забирає. Сплячий ПК — не поломка; якщо він
# мовчить добу, про це скаже перевірка 6 (разом із кількістю транскриптів).
# Звіт ПК шле ПІСЛЯ pull (Send-PcStatus в кінці синку), тож перегонів
# «звіт свіжий, а pull ще не встиг» немає.
PCFILE="$BASE/state/pc-status.env"
pc_age_min=999999
[ -f "$PCFILE" ] && pc_age_min=$(( ( $(date +%s) - $(stat -c %Y "$PCFILE") ) / 60 ))
stuck_out=$(find "$BASE/outgoing" -type f -name '*.md' -mmin +$OUTGOING_STUCK_MIN 2>/dev/null | wc -l)
out_hour=$(date +%-H)
# Умова рахується завжди, а от кричати можна лише вдень. Знімати штамп теж
# дозволено цілодобово: інакше алерт, що погас уночі, лишався б "озброєним"
# до ранку і рецидив прилетів би не одразу, а через кулдаун.
if [ "$stuck_out" -gt 0 ] && [ "$pc_age_min" -le "$PC_AWAKE_MIN" ] \
   && [ "$out_hour" -ge "$OUTGOING_QUIET_END" ] && [ "$out_hour" -lt "$OUTGOING_QUIET_START" ]; then
    names=$(find "$BASE/outgoing" -type f -name '*.md' -mmin +$OUTGOING_STUCK_MIN -printf '  %P\n' 2>/dev/null | head -5)
    fire outgoing_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: ПК на звʼязку, але транскрипти не забирає" \
        "" \
        "ПК звітував $pc_age_min хв тому, а $stuck_out файл(ів) лежать у outgoing понад $((OUTGOING_STUCK_MIN/60)) год:" \
        "$names" \
        "" \
        "Синк ходить, отже падає саме pull. Дивись у sync-лозі на ПК рядки pull з ERROR.")"
elif [ "$stuck_out" -eq 0 ] || [ "$pc_age_min" -gt "$PC_AWAKE_MIN" ]; then
    clear_alert outgoing_stuck
fi

# --- 2. Класифікатор не впізнав дисципліну -----------------------------------
nrev=$(find "$BASE/_needs-review" -type f 2>/dev/null | wc -l)
if [ "$nrev" -gt 0 ]; then
    names=$(find "$BASE/_needs-review" -type f -printf '  %P\n' 2>/dev/null | head -5)
    fire needs_review "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: потрібен ручний розбір" \
        "" \
        "$nrev запис(ів) у _needs-review — класифікатор не впізнав дисципліну." \
        "$names" \
        "" \
        "Відео збережене, на YouTube не залите.")"
else
    clear_alert needs_review
fi

# --- 3. Відео залите, але не обробляється ------------------------------------
# Поки whisper крутиться, черга — це норма, не збій. Алерт лише коли нічого
# не працює, а файли лежать.
stuck_in=$(find "$BASE/incoming" -type f ! -name '*.uploading' -mmin +$INCOMING_STUCK_MIN 2>/dev/null | wc -l)
# Рахувати ТІЛЬКИ python конвеєра, за шляхом до скрипта. Просте `pgrep -c python`
# ловило все підряд: copyparty зі стека Music Cloud і app.poller з Air Alerts
# крутяться на VPS постійно, тому busy ніколи не дорівнював нулю — і перевірка
# не могла спрацювати в принципі. Знайдено тестом 07.09.2026; обидва сервіси
# зʼявились на VPS уже після того, як сторожа написали й "перевірили".
# Урок той самий, що в 005: зламана перевірка мовчить так само, як здорова.
busy=$(pgrep -c -f "$BASE/bin/(process|transcribe_worker)\.py" || true)
# Важкий тест тримає lock конвеєра — черга стоїть очікувано (26.09.2026 тест
# нарізки тримав lock 4.7 год і розбудив цей алерт хибно).
maint=0
[ -f "$MAINT" ] && [ "$(stat -c %Y "$MAINT")" -gt "$(date +%s)" ] && maint=1
if [ "$stuck_in" -gt 0 ] && [ "${busy:-0}" -eq 0 ] && [ "$maint" -eq 0 ]; then
    names=$(find "$BASE/incoming" -type f ! -name '*.uploading' -mmin +$INCOMING_STUCK_MIN -printf '  %P\n' 2>/dev/null | head -5)
    fire incoming_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: обробка стоїть" \
        "" \
        "$stuck_in відео лежать в incoming понад $((INCOMING_STUCK_MIN/60)) год, і жоден python не працює:" \
        "$names" \
        "" \
        "Дивись ~/lectures/logs/process.log і run.log.")"
else
    clear_alert incoming_stuck
fi

# --- 4. Нові ERROR у process.log ---------------------------------------------
errfile="$STATE/process_errors.count"
# `grep -c` друкує "0" І виходить з кодом 1, коли збігів немає, тож звичне
# `|| echo 0` дописувало ДРУГИЙ нуль: у файл лягало "0\n0", а наступне
# порівняння [ 1 -gt "0\n0" ] падало з integer expression expected — у cron
# непомітно. Перевірка ламалась саме в тому стані, з якого мала починати:
# коли помилок ще жодної. Тому — санітизація обох чисел, а не `|| echo`.
cur=$(grep -c ' ERROR ' "$BASE/logs/process.log" 2>/dev/null || true)
[[ "$cur" =~ ^[0-9]+$ ]] || cur=0
if [ -f "$errfile" ]; then
    prev=$(cat "$errfile" 2>/dev/null || true)
    [[ "$prev" =~ ^[0-9]+$ ]] || prev=0
    if [ "$cur" -gt "$prev" ]; then
        lines=$(grep ' ERROR ' "$BASE/logs/process.log" 2>/dev/null | tail -3)
        fire process_error "$(printf '%s\n' \
            "⚠️ Конвеєр лекцій: нові помилки обробки" \
            "" \
            "$(( cur - prev )) нов(их) ERROR у process.log:" \
            "$lines")"
    else
        # Штамп ОБОВ'ЯЗКОВО знімати, коли нових помилок немає. Ця перевірка
        # довго була єдиною з одинадцяти без clear_alert — і мовчки з'їдала
        # помилки. Умова тут не стан, а подія («лічильник виріс»), тож штамп,
        # поставлений раз, лишався назавжди, а кулдаун 6 год глушив усе
        # наступне. Доведено на живому прикладі 09.09.2026: ERROR об 11:43
        # прилетів, а OOM о 12:11 — ні, бо штамп був віком 26 хвилин.
        # Тепер після спокійного прогону штамп зникає, і наступна помилка
        # доходить одразу — як і в решти десяти перевірок.
        clear_alert process_error
    fi
# Перший запуск: тільки запам'ятовуємо базу. Історичні помилки — не новина,
# і сторож, який на встановленні одразу кричить про минуле, вчить його ігнорувати.
fi
echo "$cur" > "$errfile"

# --- 5. Архів не порожніє: YouTube так і не підтвердив обробку ----------------
stuck_arch=$(find "$BASE/archive" -type f -mtime +$ARCHIVE_STUCK_DAYS 2>/dev/null | wc -l)
if [ "$stuck_arch" -gt 0 ]; then
    names=$(find "$BASE/archive" -type f -mtime +$ARCHIVE_STUCK_DAYS -printf '  %P\n' 2>/dev/null | head -5)
    fire archive_stuck "$(printf '%s\n' \
        "⚠️ Конвеєр лекцій: архів не порожніє" \
        "" \
        "$stuck_arch відео старші за $ARCHIVE_STUCK_DAYS днів усе ще в archive/ —" \
        "YouTube не підтвердив uploadStatus=processed:" \
        "$names" \
        "" \
        "Файли навмисно не видаляються."         "Перевірка: відкрий відео на YouTube за id зі state.db — якщо його там"         "немає або воно відхилене, лекція є лише в цьому архіві.")"
else
    clear_alert archive_stuck
fi

# =============================================================================
#  Перевірки боку ПК. ПК звітує фактами у state/pc-status.env на кожному синку,
#  судить усе одно VPS — щоб уся логіка алертів лишалась в одному місці, а на
#  ПК не треба було ані токена, ані порогів.
# =============================================================================
pcval() { grep -m1 "^$1=" "$PCFILE" 2>/dev/null | cut -d= -f2- ; }

# ціла частина числа, стійка і до коми, і до крапки: ПК під українською
# локаллю одного разу вже прислав "36,4", і порівняння тихо не спрацювало
pcint() { local v; v=$(pcval "$1"); v="${v%%[.,]*}"; [ -n "$v" ] && printf '%s' "$v" || printf '%s' ""; }

if [ -f "$PCFILE" ]; then
    hour=$(date +%-H)

    # --- 6. ПК не виходить на звʼязок добу -----------------------------------
    # Година-дві мовчання — ПК спить, це норма (27.09.2026). Кричимо, коли
    # минула доба: тоді все, що лежить в outgoing, існує лише на VPS.
    if [ "$hour" -ge "$PC_QUIET_END" ] && [ "$hour" -lt "$PC_QUIET_START" ] \
       && [ "$pc_age_min" -gt "$PC_STALE_MIN" ]; then
        n_wait=$(find "$BASE/outgoing" -type f -name '*.md' 2>/dev/null | wc -l)
        fire pc_stale "$(printf '%s\n' \
            "⚠️ ПК не виходив на звʼязок понад добу" \
            "" \
            "Останній звіт від ПК — $(( pc_age_min / 60 )) год $(( pc_age_min % 60 )) хв тому." \
            "На VPS чекають забору транскриптів: $n_wait." \
            "" \
            "Увімкни ПК — синк забере все сам. Якщо ПК вмикався, а звітів немає —"             "дивись хвіст sync-логу і LastTaskResult задачі.")"
    else
        [ "$pc_age_min" -le "$PC_STALE_MIN" ] && clear_alert pc_stale
    fi

    # --- 7. Місце на диску ПК ------------------------------------------------
    disk_free=$(pcint disk_free_gb)
    if [ -n "$disk_free" ] && [ "$disk_free" -ge 0 ] 2>/dev/null \
       && [ "$disk_free" -lt "$PC_DISK_MIN_GB" ]; then
        fire pc_disk "$(printf '%s\n' \
            "⚠️ Мало місця на ПК" \
            "" \
            "На C: лишилось $(pcval disk_free_gb) ГБ з $(pcval disk_total_gb)." \
            "Одна пара — 300-400 МБ. Забитий диск = OBS тихо не запише.")"
    else
        clear_alert pc_disk
    fi

    # --- 8. Записи лежать на ПК незалитими -----------------------------------
    # Дзеркало перевірки outgoing: VPS сам їх не бачить у принципі.
    p_old=$(pcint pending_oldest_h)
    p_cnt=$(pcval pending_count)
    if [ -n "$p_old" ] && [ "$p_old" -gt "$PC_PENDING_MAX_H" ] 2>/dev/null; then
        fire pc_pending "$(printf '%s\n' \
            "⚠️ Записи застрягли на ПК" \
            "" \
            "$p_cnt запис(ів) лежать у Videos\\Lectures вже $(pcval pending_oldest_h) год і не заливаються:" \
            "  $(pcval pending_names)" \
            "" \
            "Дивись хвіст sync-логу: чи є там ERROR або WARN про ssh.")"
    else
        clear_alert pc_pending
    fi

    # --- 9. Задачу регулярно вбиває таймліміт --------------------------------
    to=$(pcint task_timeouts_24h)
    if [ -n "$to" ] && [ "$to" -ge "$PC_TIMEOUTS_MAX" ] 2>/dev/null; then
        fire pc_timeouts "$(printf '%s\n' \
            "⚠️ Синк регулярно не встигає" \
            "" \
            "За добу задачу $to раз(и) вбито за ExecutionTimeLimit (подія 329)." \
            "Якщо між ними немає рядків ПІДТВЕРДЖЕНО — PT30M замалий," \
            "або щось стабільно висне. Це не самолікується.")"
    else
        clear_alert pc_timeouts
    fi

    # --- 10. (прибрано 27.09.2026) батарея перед ніччю -----------------------
    # Існувала заради нічного запуску о 23:00, а пробудження з Modern Standby
    # апаратно не працює (003, 014) — алерт захищав те, чого не буває.
    clear_alert pc_battery
fi

# --- 11. Був день пар, а жодного запису немає --------------------------------
# ЄДИНА відмова, яка й досі втрачає лекцію безповоротно: OBS не записав.
# Конвеєр знає лише про файли, які існують, тому без цієї перевірки мовчазна
# відсутність запису виглядає точно як вихідний.
# Дні пар — у LECTURE_DAYS на початку файлу, там же й обґрунтування кожного дня.
#
# Обмеження, про яке варто пам'ятати: перевірка питає "чи є хоч один запис", а
# не "чи всі". У четвер пар чотири-п'ять — відсутність однієї з них ця умова не
# побачить. Порахувати очікувану кількість на день — окрема правка (P2).
hour=$(date +%-H)

# скільки записів очікуємо саме сьогодні — з календаря (порожньо або 0 = не
# день онлайн-пар; календар недоступний — перевірка мовчить, а про сам
# календар кричить перевірка 16, щоб не множити два алерти на одну причину)
expect=""
if [ "$hour" -ge "$RECORDING_CHECK_HOUR" ]; then
    expect=$($EXPECT_CMD "$(date +%F)" 2>/dev/null || true)
    { [[ "$expect" =~ ^[0-9]+$ ]] && [ "$expect" -gt 0 ]; } || expect=""
fi

if [ -n "$expect" ]; then
    today_iso=$(date +%F)
    # Рахуємо ВІДЕО, і кожне рівно один раз. Запис завжди лежить рівно в одному
    # місці: incoming (чекає обробки), archive (оброблено), _needs-review (не
    # впізнано класифікатором).
    #
    # outgoing свідомо НЕ рахуємо: транскрипт там відповідає відео, яке вже
    # полічене в archive, тобто одна лекція йшла за дві. Поки поріг був "хоч
    # щось", це було нешкідливо; для порогу "менше за N" — ламає все.
    # `! -name *.md` теж не косметика: у _needs-review поруч із відео лежить
    # нотатка, і її імʼя так само містить сьогоднішню дату.
    seen=$(find "$BASE/incoming" "$BASE/archive" "$BASE/_needs-review"                 -type f ! -name '*.md' -name "*$today_iso*" 2>/dev/null | wc -l)

    # Плюс те, що ще лежить на ПК і не доїхало. Перетину з попереднім немає:
    # ПК рахує лише файли, які ЗАРАЗ у теці, а після push він їх видаляє.
    pc_today=$(pcint recordings_today)
    if [ -n "$pc_today" ] && [ "$pc_today" -gt 0 ] 2>/dev/null; then
        seen=$(( seen + pc_today ))
    fi

    if [ "$seen" -eq 0 ]; then
        fire no_recording "$(printf '%s
'             "❓ Сьогодні день пар, а записів немає"             ""             "За $today_iso не знайшлось жодного запису — ні на VPS, ні в черзі на ПК."             "Очікувалось: $expect."             ""             "Якщо пари були — OBS не записав, і лекція втрачена безповоротно."             "Якщо пар не було — просто зігноруй.")"
    elif [ "$seen" -lt "$expect" ]; then
        fire no_recording "$(printf '%s
'             "❓ Записів менше, ніж мало бути"             ""             "За $today_iso знайдено $seen з $expect очікуваних."             ""             "Найімовірніше одну пару не записали — перевір, поки памʼятаєш, яку."             "Якщо пара не відбулась або була офлайн — поправ її в календарі КПІ"             "(видали подію або зміни поле «Місце»), і алерт більше не повториться.")"
    else
        clear_alert no_recording
    fi
fi

# --- 12. Бекап сховища є, але не змінюється ----------------------------------
# НАВІЩО. У липні 2026 хардернінг прав забрав у бекапу доступ на читання, і той
# місяць складав порожні 45-байтні архіви. Це полагоджено перевіркою MIN_BYTES
# у самому obsidian_backup.sh. Але лишився ГІРШИЙ варіант тієї ж відмови:
# архів нормального розміру, який просто не змінюється, бо джерело застигло.
# Розмір у нормі, gzip цілий, файли щодня нові — і жодна перевірка не спрацює.
#
# Саме це знайшлось 09.09.2026 руками: obsidian_2026-09-08.tar.gz і
# obsidian_2026-09-09.tar.gz виявились ПОБАЙТОВО ідентичними. Не поломка бекапу —
# відставання клієнтського синку: Remotely Save штовхає зміни лише коли Obsidian
# відкритий, а ПК ці дні здебільшого спав. Наслідок практичний: транскрипт
# практики 08.09 і конспекти Ajax якийсь час існували в ОДНОМУ екземплярі, на ПК.
#
# Порівнюємо РОЗМІР, а не sha256: архіви по 400 МБ, хешувати їх щочверть години
# безглуздо. Збіг розмірів байт-у-байт кілька діб поспіль на 400-мегабайтному
# gzip практично неможливий, якщо джерело справді змінювалось.
if [ -d "$BACKUP_DIR" ]; then
    newest=$(ls -1t "$BACKUP_DIR"/*.tar.gz 2>/dev/null | head -1)
    if [ -n "$newest" ]; then
        b_age_h=$(( ( $(date +%s) - $(stat -c %Y "$newest" 2>/dev/null || date +%s) ) / 3600 ))
        # скільки найсвіжіших архівів мають однаковий розмір
        sizes=$(ls -1t "$BACKUP_DIR"/*.tar.gz 2>/dev/null | head -$(( BACKUP_SAME_MAX + 1 ))                 | xargs -r stat -c %s 2>/dev/null)
        n_total=$(printf '%s
' "$sizes" | grep -c . || true)
        n_uniq=$(printf '%s
' "$sizes" | sort -u | grep -c . || true)
        [[ "$n_total" =~ ^[0-9]+$ ]] || n_total=0
        [[ "$n_uniq" =~ ^[0-9]+$ ]] || n_uniq=0

        if [ "$b_age_h" -gt "$BACKUP_STALE_H" ]; then
            fire backup_stale "$(printf '%s
'                 "⚠️ Бекап сховища не оновлюється"                 ""                 "Найсвіжіший архів — $b_age_h год тому:"                 "  $(basename "$newest")"                 ""                 "Перевірка: чи ходить root-овий cron о 03:00 і чи читається джерело.")"
        elif [ "$n_total" -gt "$BACKUP_SAME_MAX" ] && [ "$n_uniq" -eq 1 ]; then
            fire backup_stale "$(printf '%s
'                 "⚠️ Бекап робиться, але сховище в ньому застигло"                 ""                 "$n_total останніх архівів мають ОДНАКОВИЙ розмір — джерело не змінюється."                 "Сам бекап справний, застряг клієнтський синк."                 ""                 "Перевірка: відкрий Obsidian і дай Remotely Save доробити."                 "Поки цього не сталось, свіжі нотатки існують в одному екземплярі — на ПК.")"
        else
            clear_alert backup_stale
        fi
    fi
fi

# --- 13. Нічний апдейт: помітний результат -----------------------------------
# Подієва умова, той самий патерн, що 4 (після фіксу інциденту 010): рахуємо
# рядки в лозі, порівнюємо з попереднім прогоном, і якщо зʼявилось щось нове —
# дивимось, чи воно "помітне". "Помітне" — це skipped_busy (апдейт пропущено,
# а не тихо відкладено), apt_error, services_ok=no (щось не піднялось після
# ребуту), або реальний результат (upgraded>0 / reboot_required=yes). Пакети
# ПОЗА security (docker-ce тощо, held python3.11) свідомо НЕ входять сюди —
# Роман 10.09.2026: рядок у лозі досить, без сповіщення (див. vps-nightly-
# update.sh, поле pending_other).
ulf="$STATE/update_log.lines"
if [ -f "$UPDATE_LOG" ]; then
    cur_lines=$(wc -l < "$UPDATE_LOG" 2>/dev/null || true)
else
    cur_lines=0
fi
[[ "$cur_lines" =~ ^[0-9]+$ ]] || cur_lines=0
prev_lines=$(cat "$ulf" 2>/dev/null || true)
[[ "$prev_lines" =~ ^[0-9]+$ ]] || prev_lines=0

notable=""
if [ "$cur_lines" -gt "$prev_lines" ]; then
    new_lines=$(tail -n $(( cur_lines - prev_lines )) "$UPDATE_LOG" 2>/dev/null)
    notable=$(printf '%s\n' "$new_lines" \
        | grep -E 'result=skipped_busy|result=apt_error|services_ok=no|upgraded=[1-9]|reboot_required=yes' \
        || true)
fi

if [ -n "$notable" ]; then
    # Переклад сирих key=value рядків у людську мову: речення кажуть, що саме
    # сталося, у дужках лишається лише ЧАС для довідки — той самий принцип,
    # що вже застосований в алертах 1, 5 і 6 (lecture-pipeline.md, "Алерт має
    # називати перевірку, а не причину"). Логіку "що вважати помітним" вище
    # не чіпаємо — лише текст, який з нею йде в телеграм.
    #
    # Перша версія цієї правки (16.09.2026) досі тягла в дужки ВЕСЬ сирий
    # рядок — з довгим pending_other (докер, netplan) це виглядало так само
    # технічно, як і "до". Роман показав живий приклад 17.09.2026: дужки
    # лишили, але звузили до часу події — повний рядок і так є в $UPDATE_LOG.
    human=()
    while IFS= read -r line; do
        [ -z "$line" ] && continue
        ts=$(printf '%s' "$line"         | sed -n 's/^\([0-9-]\{10\} [0-9:]\{8\}\).*/\1/p')
        result=$(printf '%s' "$line"     | sed -n 's/.*result=\([^ ]*\).*/\1/p')
        upgraded=$(printf '%s' "$line"   | sed -n 's/.*upgraded=\([0-9]*\).*/\1/p')
        pkgs=$(printf '%s' "$line"       | sed -n 's/.*pkgs="\([^"]*\)".*/\1/p')
        reboot_req=$(printf '%s' "$line" | sed -n 's/.*reboot_required=\([^ ]*\).*/\1/p')
        rebooted=$(printf '%s' "$line"   | sed -n 's/.*rebooted=\([^ ]*\).*/\1/p')
        services_ok=$(printf '%s' "$line" | sed -n 's/.*services_ok=\([^ ]*\).*/\1/p')
        failed=$(printf '%s' "$line"     | sed -n 's/.*failed="\([^"]*\)".*/\1/p')
        busy_at_reboot=$(printf '%s' "$line" | sed -n 's/.*busy_at_reboot=\([^ ]*\).*/\1/p')

        block=()
        case "$result" in
            skipped_busy)
                block+=("Пропущено — сервер був зайнятий транскрипцією чи класифікацією, спробує наступної ночі.") ;;
            apt_error)
                block+=("apt-оновлення впало з помилкою — дивись $UPDATE_LOG.")
                block+=("Стан перезапуску невідомий — до цієї перевірки апдейт не дійшов.")
                ;;
            ok)
                # Роман, 17.09.2026: писати перезапуск явно завжди, а не лише
                # коли він стався чи потрібен — мовчання про цю тему теж
                # читається як питання без відповіді.
                if [ -n "$upgraded" ] && [ "$upgraded" -gt 0 ]; then
                    if [ -n "$pkgs" ]; then
                        block+=("Оновлено пакетів: $upgraded ($pkgs).")
                    else
                        block+=("Оновлено пакетів: $upgraded.")
                    fi
                else
                    block+=("Перевірено, оновлювати не було чого.")
                fi
                if [ "$rebooted" = "yes" ]; then
                    block+=("Сервер перезавантажився.")
                elif [ "$reboot_req" = "yes" ] && [ "$busy_at_reboot" = "yes" ]; then
                    block+=("Перезапуск потрібен, але відкладено — сервер був зайнятий.")
                elif [ "$reboot_req" = "yes" ]; then
                    block+=("Перезапуск потрібен, ще не відбувся.")
                else
                    block+=("Перезапуск не був потрібен.")
                fi
                ;;
        esac
        if [ "$services_ok" = "no" ]; then
            if [ -n "$failed" ]; then
                block+=("Після перезавантаження не піднялись служби: $failed.")
            else
                block+=("Після перезавантаження не всі служби піднялись самі.")
            fi
        fi
        # Захист від майбутнього поля, яке grep вище зловив, а case — ні:
        # мовчати тут так само небезпечно, як інцидент 010 (штамп без clear_alert).
        [ "${#block[@]}" -eq 0 ] && block+=("Позначено як помітне, але не впізнав поле — дивись $UPDATE_LOG.")

        human+=("${block[@]}")
        [ -n "$ts" ] && human+=("($ts)")
    done <<< "$notable"

    fire nightly_update "$(printf '%s\n' \
        "🔧 Нічний апдейт VPS" \
        "" \
        "${human[@]}")"
else
    clear_alert nightly_update
fi
echo "$cur_lines" > "$ulf"

# --- 14. Нічний апдейт мовчить понад місяць -----------------------------------
# Станова умова (на відміну від 13): дивимось не на нову подію, а на те, скільки
# часу минуло від ОСТАННЬОГО result=ok. skipped_busy і apt_error в рахунок не
# йдуть — вони не підтверджують, що апдейт справді перевірено.
#
# Коли давно нема result=ok, причину не вгадуємо, а читаємо з останніх
# UPDATE_LOOKBACK рядків result=: більшість skipped_busy → стабільно зайнятий;
# є apt_error → apt падає; рядків result= взагалі нема → root-крон не ходить.
#
# Навмисно БЕЗ "if [ -f "$UPDATE_LOG" ]" навколо всього блоку: якщо файл
# узагалі не існує (root-крон ніколи не ставили чи хтось видалив лог), це теж
# має кричати, а не тихо пропускати перевірку — той самий урок, що інциденти
# 005/007/010: зламана перевірка не повинна виглядати як здоровий стан.
if [ -f "$UPDATE_LOG" ]; then
    last_ok_line=$(grep 'result=ok' "$UPDATE_LOG" 2>/dev/null | tail -1)
    first_line=$(head -1 "$UPDATE_LOG" 2>/dev/null)
else
    last_ok_line=""
    first_line=""
fi

if [ -n "$last_ok_line" ]; then
    last_ok_date=$(printf '%s' "$last_ok_line" | awk '{print $1}')
    last_ok_epoch=$(date -d "$last_ok_date" +%s 2>/dev/null || echo 0)
    stale_days=$(( ( $(date +%s) - last_ok_epoch ) / 86400 ))
elif [ -n "$first_line" ]; then
    # ЖОДНОГО result=ok ще не було, але лог не порожній. Знайдено живцем
    # 10.09.2026, годину по встановленню: перший прогін після установки був
    # skipped_busy (чергу ще не розібрано), і БЕЗ цієї гілки stale_days одразу
    # ставав 999999 — щойно поставлений root-крон кричав "мовчить понад 30
    # днів", хоча логу було кілька годин. Правильне питання не "чи БУЛО
    # result=ok", а "чи ДОСИТЬ ЧАСУ минуло без нього" — тому рахуємо від
    # НАЙСТАРІШОГО рядка (моменту встановлення), а не вдаємо нескінченність.
    first_date=$(printf '%s' "$first_line" | awk '{print $1}')
    first_epoch=$(date -d "$first_date" +%s 2>/dev/null || echo 0)
    stale_days=$(( ( $(date +%s) - first_epoch ) / 86400 ))
else
    # Лог порожній або не існує взагалі — тут і справді нема жодних даних,
    # і мовчати не можна: якщо root-крон мав ставитись, а файлу нема, це саме
    # та проблема, яку перевірка існує ловити.
    stale_days=999999
fi

if [ "$stale_days" -gt "$UPDATE_STALE_DAYS" ]; then
    recent=$(grep 'result=' "$UPDATE_LOG" 2>/dev/null | tail -"$UPDATE_LOOKBACK")
    recent_n=$(printf '%s\n' "$recent" | grep -c . || true)
    busy_n=$(printf '%s\n' "$recent" | grep -c 'result=skipped_busy' || true)
    err_n=$(printf '%s\n' "$recent" | grep -c 'result=apt_error' || true)
    [[ "$recent_n" =~ ^[0-9]+$ ]] || recent_n=0
    [[ "$busy_n" =~ ^[0-9]+$ ]] || busy_n=0
    [[ "$err_n" =~ ^[0-9]+$ ]] || err_n=0

    if [ "$recent_n" -eq 0 ]; then
        reason="скрипт узагалі не запускався — перевір root-крон (sudo crontab -l) і сам файл $UPDATE_LOG"
    elif [ "$busy_n" -gt 0 ] && [ "$busy_n" -ge $(( recent_n / 2 )) ]; then
        reason="стабільно зайнятий: $busy_n з останніх $recent_n прогонів пропущено через whisper/ollama/чергу"
    elif [ "$err_n" -gt 0 ]; then
        reason="apt падає: $err_n з останніх $recent_n прогонів result=apt_error, дивись $UPDATE_LOG"
    else
        reason="прогони йдуть, але жоден не result=ok понад $UPDATE_STALE_DAYS днів — розібратись вручну"
    fi

    fire nightly_update_stale "$(printf '%s\n' \
        "⚠️ Нічний апдейт VPS мовчить понад $UPDATE_STALE_DAYS днів" \
        "" \
        "Причина: $reason")"
else
    clear_alert nightly_update_stale
fi

# --- 15. Розклад втрутився в класифікацію ------------------------------------
# З 21.09.2026 classify._apply_schedule() може переважити голоси моделі розкладом
# або відправити запис у _needs-review, бо голоси суперечать розкладу. Це
# ПОДІЯ, а не стан — той самий патерн, що в перевірці 4: лічильник рядків
# SCHEDULE_HINT у process.log + clear_alert, коли приросту немає (інакше штамп
# висів би 6 годин і глушив наступні події).
#
# Навіщо взагалі кричати: розклад сам може бути хибним (пари перенесли, а
# SCHEDULE у timetable.py не оновили). Тоді перший ж збій мовчки лягав би в
# чужий плейліст або в _needs-review без пояснення. Повідомлення називає
# запис, голоси й що перевірити.
hintfile="$STATE/schedule_hint.count"
hcur=$(grep -c 'SCHEDULE_HINT:' "$BASE/logs/process.log" 2>/dev/null || true)
[[ "$hcur" =~ ^[0-9]+$ ]] || hcur=0
if [ -f "$hintfile" ]; then
    hprev=$(cat "$hintfile" 2>/dev/null || true)
    [[ "$hprev" =~ ^[0-9]+$ ]] || hprev=0
    if [ "$hcur" -gt "$hprev" ]; then
        hlines=$(grep 'SCHEDULE_HINT:' "$BASE/logs/process.log" 2>/dev/null | tail -3 | sed 's/^[0-9-]* [0-9:,]* [A-Z]* //')
        fire schedule_hint "$(printf '%s\n' \
            "ℹ️ Конвеєр лекцій: розклад втрутився в класифікацію" \
            "" \
            "$(( hcur - hprev )) нов(их) випадків:" \
            "$hlines" \
            "" \
            "«календар …, але голоси одностайно …» — усі три фрагменти проти календаря, запис у _needs-review: найімовірніше пару замінили, а календар КПІ не оновили." \
            "«розклад переважив» / «суперечать розкладу» — запис зачепив кілька пар календаря, і вибір між ними робили голоси: перевір дисципліну." \
            "Розібрати вручну: resolve_review.py (див. lecture-pipeline.md).")"
    else
        clear_alert schedule_hint
    fi
# Перший запуск: лише запам'ятовуємо базу (як у перевірці 4).
fi
echo "$hcur" > "$hintfile"

# --- 16. Календар КПІ не оновлюється ----------------------------------------
# Календар — джерело правди для дисципліни (27.09.2026). Якщо кеш застиг
# (адресу відкликали, Google змінив формат, мережа), класифікація тихо
# повертається до чистого LLM — тобто до помилок на кшталт 26.09. Немає
# файлу з адресою = календар не налаштований, це не збій.
if [ -f "$CAL_URL" ]; then
    if [ ! -f "$CAL_CACHE" ] || [ -n "$(find "$CAL_CACHE" -mmin +$(( CAL_STALE_H * 60 )) 2>/dev/null)" ]; then
        last=$(grep 'календар КПІ: error\|календар не оновився' "$BASE/logs/process.log" 2>/dev/null | tail -1 | sed 's/^[0-9-]* [0-9:,]* [A-Z]* //')
        fire calendar_stale "$(printf '%s\n' \
            "⚠️ Конвеєр лекцій: календар КПІ не оновлюється" \
            "" \
            "Кеш старший за $CAL_STALE_H год (або його немає). Дисципліну зараз визначає лише модель." \
            "Остання помилка: ${last:-немає в process.log}" \
            "" \
            "Перевірка: ~/lectures/venv/bin/python ~/lectures/bin/timetable.py refresh --force" \
            "Якщо «HTTP Error 404» — секретну адресу скинули, візьми нову в налаштуваннях календаря.")"
    else
        clear_alert calendar_stale
    fi
fi

# --- 16a. Календар Ajax не оновлюється ---------------------------------------
# Те саме для календаря «AJAX Intership» (30.09.2026): без нього заняття Ajax
# знову класифікує лише модель — саме так 29.09 Altium поїхав у Матаналіз (021).
if [ -f "$AJAX_CAL_URL" ]; then
    if [ ! -f "$AJAX_CAL_CACHE" ] || [ -n "$(find "$AJAX_CAL_CACHE" -mmin +$(( CAL_STALE_H * 60 )) 2>/dev/null)" ]; then
        last=$(grep 'календар Ajax: error\|календар Ajax не оновився' "$BASE/logs/process.log" 2>/dev/null | tail -1 | sed 's/^[0-9-]* [0-9:,]* [A-Z]* //')
        fire calendar_ajax_stale "$(printf '%s\n' \
            "⚠️ Конвеєр лекцій: календар Ajax не оновлюється" \
            "" \
            "Кеш старший за $CAL_STALE_H год (або його немає). Заняття Ajax зараз визначає лише модель." \
            "Остання помилка: ${last:-немає в process.log}" \
            "" \
            "Перевірка: ~/lectures/venv/bin/python ~/lectures/bin/timetable.py refresh-ajax --force" \
            "Якщо «HTTP Error 404» — секретну адресу скинули, візьми нову в налаштуваннях календаря «AJAX Intership».")"
    else
        clear_alert calendar_ajax_stale
    fi
fi

# --- 17. Транскрипт вийшов з дірками, петлями чи сміттям -----------------------
# З 29.09.2026 process.check_quality() (transcript_quality.py) логує QUALITY_WARN,
# коли в записі є хвилини зі звуком без тексту, петлі повторів чи сміття.
# Навіщо: 27-29.09 зміни декодування двічі тихо псували текст (половина лекції
# зникла, сотні повторених рядків), і знаходили це лише ручні звірки. Подія, а
# не стан — той самий патерн лічильника, що в перевірці 15.
qfile="$STATE/quality_warn.count"
qcur=$(grep -c 'QUALITY_WARN:' "$BASE/logs/process.log" 2>/dev/null || true)
[[ "$qcur" =~ ^[0-9]+$ ]] || qcur=0
if [ -f "$qfile" ]; then
    qprev=$(cat "$qfile" 2>/dev/null || true)
    [[ "$qprev" =~ ^[0-9]+$ ]] || qprev=0
    if [ "$qcur" -gt "$qprev" ]; then
        qlines=$(grep 'QUALITY_WARN:' "$BASE/logs/process.log" 2>/dev/null | tail -3 | sed 's/^[0-9-]* [0-9:,]* [A-Z]* QUALITY_WARN: //')
        fire quality_warn "$(printf '%s\n' \
            "🔎 Конвеєр лекцій: транскрипт з вадами" \
            "" \
            "$(( qcur - qprev )) нов(их) випадків:" \
            "$qlines" \
            "" \
            "«дірки» — хвилини, де в записі є звук, а тексту нема: або whisper загубив мовлення, або там гучний шум без слів. Звір із відео на YouTube." \
            "«петлі» — одна фраза повторюється поспіль; «сміття» — ієрогліфи/хангиль на шумі." \
            "Відео вже на YouTube, обробка не зупинялась. Якщо таке повторюється на кількох записах — регресія декодування (див. lecture-pipeline.md).")"
    else
        clear_alert quality_warn
    fi
fi
echo "$qcur" > "$qfile"

