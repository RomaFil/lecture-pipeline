"""Розклад як ПІДКАЗКА для класифікатора — не як правило.

Класифікатор (classify.py) голосує за дисципліну по трьох фрагментах, і на справжніх
записах хибна більшість 2/3 з `confidence: high` трапляється приблизно в кожному
п'ятому записі (tests/collect_votes.py, 20.09.2026). Час запису — незалежний від
тексту сигнал: у чверг о 10:25 йде фізика, хоч би що модель почула про «коливання».

Чому це НЕ таблиця «день + пара → дисципліна» з першої версії конвеєра, яку тоді
відкинули (вона ламалась на першому ж перенесенні): тут розклад ніколи не
призначає дисципліну сам. Він лише перевіряє голоси й розв'язує розбіжності
(див. classify._apply_schedule), а одностайні 3/3 не переважує ніколи. Застарілий
рядок у цій таблиці коштує максимум зайвого запису в _needs-review, а не
мовчазного промаху в чужий плейліст.

Дані — з реальних записів 03–19.09.2026 (старт береться з імені файлу OBS, а не з
mtime, який OBS оновлює рідко). Вікна — за сіткою пар КПІ, з запасом. Один слот може
мати кілька кандидатів: у суботу о 14:15 бувають і ОТК (12.09), і англійська (19.09) —
чергування тижнів. Змінився розклад — правити SCHEDULE тут; вимкнути підказку цілком:
LECTURE_SCHEDULE_HINT=0.

День тижня: 0 = Пн … 6 = Нд.
"""
import os
from datetime import datetime

# (день, початок, кінець, код дисципліни з classify.SUBJECTS)
SCHEDULE = [
    # Вт
    (1, "08:30", "10:00", "ТЕОРІЯ_КІЛ"),      # лабораторна ОТК (15.09 08:45)
    (1, "10:25", "12:00", "ТЕОРІЯ_КІЛ"),      # практика ОТК (15.09 10:53)
    (1, "14:15", "15:45", "МАТАНАЛІЗ"),       # практика (08.09, 15.09 14:17)
    (1, "17:00", "20:00", "АЯКС"),
    # Ср
    (2, "14:15", "15:45", "БОКС"),
    # Чт
    (3, "08:30", "10:00", "СХЕМОТЕХНІКА"),
    (3, "10:25", "12:00", "ФІЗИКА"),
    (3, "12:20", "13:50", "МАТАНАЛІЗ"),
    (3, "14:15", "19:00", "ТЕОРІЯ_КІЛ"),      # здвоєна лекція, у записах до ~18:00
    (3, "17:00", "20:00", "АЯКС"),
    # Пт
    (4, "12:20", "13:50", "МЕРЕЖІ_CISCO"),
    (4, "18:00", "22:00", "МЕРЕЖІ_CISCO"),    # вечірня лекція: початок 18:05 і 20:37
    # Сб
    (5, "08:30", "10:15", "ТЕОРІЯ_КІЛ"),
    (5, "10:25", "12:00", "ФІЗИКА"),
    (5, "12:20", "13:50", "АНГЛІЙСЬКА"),
    (5, "14:15", "15:45", "ТЕОРІЯ_КІЛ"),      # чергування тижнів: 12.09 — ОТК ...
    (5, "14:15", "15:45", "АНГЛІЙСЬКА"),      # ... 19.09 — англійська
]

# Скільки хвилин запису мусить припадати на слот, щоб слот вважався очікуваним.
MIN_OVERLAP_MIN = 20
# Короткий запис (обірваний, старт із запізненням) — досить половини його довжини.
MIN_OVERLAP_SHARE = 0.5


def _minutes(t: str) -> int:
    h, m = t.split(":")
    return int(h) * 60 + int(m)


def expected_subjects(start: datetime, end: datetime) -> set:
    """Коди дисциплін, які за розкладом мали йти в інтервалі запису [start, end].

    Порожня множина = розклад нічого не знає про цей час (запис поза пар: Ajax
    в іншу годину, тренування, тестовий кліп) — тоді підказки немає й класифікатор
    працює як без неї. Запис, що перетнув північ, розкладом не обслуговується.
    """
    if os.getenv("LECTURE_SCHEDULE_HINT", "1") == "0" or end <= start:
        return set()
    if start.date() != end.date():
        return set()
    s, e = start.hour * 60 + start.minute, end.hour * 60 + end.minute
    length = e - s
    found = set()
    for day, a, b, code in SCHEDULE:
        if day != start.weekday():
            continue
        overlap = min(e, _minutes(b)) - max(s, _minutes(a))
        if overlap >= MIN_OVERLAP_MIN or (overlap > 0 and overlap >= MIN_OVERLAP_SHARE * length):
            found.add(code)
    return found
